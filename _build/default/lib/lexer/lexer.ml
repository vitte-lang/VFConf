exception Error of {
  message : string;
  start_pos : Lexing.position;
  end_pos : Lexing.position;
}

let error lexbuf message =
  raise
    (Error
       {
         message;
         start_pos = Lexing.lexeme_start_p lexbuf;
         end_pos = Lexing.lexeme_end_p lexbuf;
       })

let newline lexbuf =
