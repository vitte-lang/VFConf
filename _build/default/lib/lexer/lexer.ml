let keyword_or_identifier value =
  match Keyword.of_string value with
  | Some Keyword.Include -> INCLUDE
  | Some Keyword.Define -> DEFINE
  | Some Keyword.When -> WHEN
  | Some Keyword.Else -> ELSE

  | Some Keyword.True
  | Some Keyword.On ->
      BOOLEAN true

  | Some Keyword.False
  | Some Keyword.Off ->
      BOOLEAN false

  | Some Keyword.Null
  | Some Keyword.None ->
      NULL

  | Some Keyword.Rgb ->
      RGB

  | Some Keyword.Rgba ->
      RGBA

  | None ->
      IDENTIFIER value

let parse_color lexbuf value =
  let length = String.length value in

  if
    length = 4
    || length = 5
    || length = 7
    || length = 9
  then
    COLOR value
  else
    error lexbuf (Invalid_color value)

let parse_duration lexbuf number unit_ =
  let amount =
    parse_float lexbuf number
  in
  DURATION (amount, unit_)

let parse_size lexbuf number unit_ =
  let amount =
    parse_float lexbuf number
  in
  SIZE (amount, unit_)

